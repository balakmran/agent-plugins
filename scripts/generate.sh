#!/usr/bin/env bash
# Writes both marketplace files and the README plugin list from catalog/*.json.
#
#   .claude-plugin/marketplace.json   Claude Code, Codex, VS Code (git-subdir sources)
#   .github/plugin/marketplace.json   Copilot CLI (github sources with a path)
#
# Entries whose sha is all zeros have never been released and are left out.
set -euo pipefail

# shellcheck source=scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require jq

files=()
while IFS= read -r f; do
  check_catalog_file "$f"
  files+=("$f")
done < <(catalog_files)

if ((${#files[@]})); then
  entries="$(jq -s --arg zero "$UNRELEASED_SHA" '[.[] | select(.sha != $zero)] | sort_by(.name)' "${files[@]}")"
else
  entries='[]'
fi

# write <file> <jq filter that builds an entry's "source" from catalog entry $e>
write() {
  local out="$1" source_filter="$2"
  mkdir -p "$(dirname "$out")"
  jq -n \
    --arg name "$MARKETPLACE_NAME" \
    --arg owner "$MARKETPLACE_OWNER" \
    --arg description "$MARKETPLACE_DESCRIPTION" \
    --argjson entries "$entries" \
    "{
      name: \$name,
      owner: { name: \$owner },
      description: \$description,
      plugins: [ \$entries[] as \$e | {
        name: \$e.name,
        description: \$e.description,
        version: \$e.version,
        category: \$e.category,
        keywords: \$e.keywords,
        source: ($source_filter)
      } ]
    }" >"$out"
}

# The filters are jq, not shell: $e must not expand here.
# shellcheck disable=SC2016
write "$CLAUDE_FILE" \
  '{ source: "git-subdir", url: "https://github.com/\($e.repo).git", path: $e.path, ref: $e.tag, sha: $e.sha }'
# shellcheck disable=SC2016
write "$COPILOT_FILE" \
  '{ source: "github", repo: $e.repo, path: $e.path, ref: $e.tag, sha: $e.sha }'

# README plugin list, between the markers.
list="$(jq -r '
  if length == 0 then
    "No plugins are published yet."
  else
    "| Plugin | Version | Description | Source |",
    "| --- | --- | --- | --- |",
    (.[] | (if .path == "." then "" else "/\(.path)" end) as $sub
      | "| `\(.name)` | \(.version) | \(.description) | [`\(.repo)\($sub)`](https://github.com/\(.repo)/tree/\(.tag)\($sub)) |")
  end' <<<"$entries")"

start='<!-- plugins:start (generated by scripts/generate.sh) -->'
end='<!-- plugins:end -->'
if ! grep -qxF "$start" "$README_FILE" || ! grep -qxF "$end" "$README_FILE"; then
  die "README.md must contain the lines '$start' and '$end'"
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
LIST="$list" awk -v start="$start" -v end="$end" '
  $0 == start { print; print ""; print ENVIRON["LIST"]; print ""; skip = 1; next }
  $0 == end   { skip = 0 }
  !skip       { print }
' "$README_FILE" >"$tmp"
cat "$tmp" >"$README_FILE"
